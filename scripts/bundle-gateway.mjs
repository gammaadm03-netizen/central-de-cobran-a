import {build} from 'esbuild';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
await mkdir('artifacts',{recursive:true});
await mkdir('supabase/dashboard',{recursive:true});
await build({entryPoints:['supabase/functions/auth-gateway/index.ts'],bundle:true,platform:'neutral',format:'esm',target:'es2022',outfile:'artifacts/auth-gateway-dashboard.ts'});
const code=await readFile('artifacts/auth-gateway-dashboard.ts','utf8');
await writeFile('supabase/dashboard/auth-gateway.ts','// Generated by npm run bundle:gateway from the reviewed handler and entrypoint.\n// Copy the complete file to index.ts in Supabase Edge Functions; contains no credentials.\n'+code);
console.log('Generated gateway files for review and dashboard copying; no deployment performed.');
